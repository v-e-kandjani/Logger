// RenderTextReport renders any of the 5 standard reports into formatted plain-text/markdown.
func RenderTextReport(report models.ComprehensiveIncidentReport) (string, error) {
	var tmplStr string
	var data any

	switch report.ReportType {
	case "exec_posture":
		tmplStr = ExecReportTemplate
		if report.ExecData != nil {
			data = report.ExecData
		} else {
			data = &models.ExecReportData{
				TenantName:       report.Tenant.TenantName,
				ReportWindow:     fmt.Sprintf("%s to %s", report.StartTime.Format("2006-01-02"), report.EndTime.Format("2006-01-02")),
				OverallPosture:   "STABLE",
				TotalAlerts:      report.TotalAlerts,
				TruePositives:    report.CriticalAlerts,
				MTTDMinutes:      float64(report.MTTDMinutes),
				MTTRMinutes:      float64(report.MTTRMinutes),
				PreventionRatio:  "98.4%",
				TopAttackedHosts: []string{"Edge-Firewall-01", "Core-Switch-02"},
				TopThreatActors:  []string{"External Brute-Force", "Distributed Scanners"},
				KeyMilestones:    []string{"All hourly Law 5651 logs sealed and verified."},
				ResourceNeeds:    []string{"Maintain edge proxy buffer health."},
			}
		}
	case "shift_handover":
		tmplStr = HandoverReportTemplate
		if report.HandoverData != nil {
			data = report.HandoverData
		} else {
			data = &models.HandoverReportData{
				TenantName:       report.Tenant.TenantName,
				ShiftID:          "Standard Shift",
				DepartingAnalyst: "Security Analyst",
				IncomingAnalyst:  "Lead Operator",
			}
		}
	case "compliance_audit":
		tmplStr = ComplianceReportTemplate
		if report.ComplianceData != nil {
			data = report.ComplianceData
		} else {
			data = &models.ComplianceReportData{
				TenantName:       report.Tenant.TenantName,
				Framework:        "Law No. 5651 & ISO/IEC 27001",
				AuditPeriod:      fmt.Sprintf("%s to %s", report.StartTime.Format("2006-01-02"), report.EndTime.Format("2006-01-02")),
				LogIntegrityPass: true,
				FailedAuthRatio:  "2.1%",
			}
		}
	case "vuln_exposure":
		tmplStr = VulnerabilityReportTemplate
		if report.VulnData != nil {
			data = report.VulnData
		} else {
			data = &models.VulnerabilityReportData{
				TenantName:   report.Tenant.TenantName,
				ReportWindow: fmt.Sprintf("%s to %s", report.StartTime.Format("2006-01-02"), report.EndTime.Format("2006-01-02")),
			}
		}
	case "incident_rca":
		fallthrough
	default:
		tmplStr = ForensicReportTemplate
		if report.ForensicData != nil {
			data = report.ForensicData
		} else {
			// Populate from ComprehensiveIncidentReport
			var killChain []models.KillChainEntry
			for _, t := range report.Timeline {
				killChain = append(killChain, models.KillChainEntry{
					Phase:     t.Source,
					Timestamp: t.Timestamp.Format("2006-01-02 15:04:05"),
					Evidence:  t.Description,
				})
			}
			var evidenceList []string
			for _, c := range report.ChainOfCustody {
				evidenceList = append(evidenceList, fmt.Sprintf("%s (%s) - SHA256: %s [Token: %s]", c.EvidenceID, c.ArtifactType, c.SHA256Hash, c.TSATokenZD))
			}
			var actionItems []models.ActionItem
			for i, p := range report.RemediationPlan {
				actionItems = append(actionItems, models.ActionItem{
					Action:   p,
					Owner:    "SOC Engineer",
					Deadline: fmt.Sprintf("+%d Days", (i+1)*3),
				})
			}
			data = &models.ForensicReportData{
				TenantName:        report.Tenant.TenantName,
				IncidentID:        report.ReportID,
				Severity:          report.Classification,
				DetectionTime:     report.StartTime.Format("2006-01-02 15:04:05 UTC"),
				ResolutionTime:    report.EndTime.Format("2006-01-02 15:04:05 UTC"),
				LeadAnalyst:       "Valtrivo SIEM Lead",
				Summary:           report.ExecutiveSummary,
				KillChainSteps:    killChain,
				EvidenceArtifacts: evidenceList,
				RootCause:         report.RootCause,
				ActionItems:       actionItems,
			}
		}
	}

	tmpl, err := template.New("report").Parse(tmplStr)
	if err != nil {
		return "", err
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return "", err
	}

	return buf.String(), nil
}
